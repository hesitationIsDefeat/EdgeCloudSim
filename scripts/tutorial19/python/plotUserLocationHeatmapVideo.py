import os
import argparse

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')  # video is rendered to a file, no display is needed
import matplotlib.pyplot as plt
import matplotlib.animation as animation
from matplotlib.lines import Line2D
from matplotlib.patches import Circle

from config import get_configuration, get_services, get_uav_hosted_services

# Simulation area boundaries in meters.
# These must match northern_bound / southern_bound / eastern_bound / western_bound
# in the scenario's default_config.properties file.
AREA_BOUNDS = {'x_min': 0, 'x_max': 1000, 'y_min': 0, 'y_max': 1000}

# One color per service for the UAV markers (cycled if there are more services than colors). They
# are kept clear of the heat map's yellow-red range so a UAV stays visible on top of a crowd.
_SERVICE_COLORS = ['tab:blue', 'tab:green', 'tab:purple', 'tab:cyan', 'tab:olive', 'tab:pink']
_EVENT_COLOR = 'black'


def _read_events_log(file_path):
    """
    Reads a *_EVENTS.log file (generated by SimLogger when the scenario has world events) into a
    list of dicts. File format: '#auto generated file!' header followed by rows of
    index;name;start;end;x;y;radius;attraction_radius;request;services
    """
    events = []
    with open(file_path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            fields = line.split(';')
            events.append({
                'name': fields[1], 'start': float(fields[2]), 'end': float(fields[3]),
                'x': float(fields[4]), 'y': float(fields[5]),
                'radius': float(fields[6]), 'attraction_radius': float(fields[7]),
                'request': fields[8],
            })
    return events


def _read_location_log(file_path, id_column):
    """
    Reads a *_USER_LOCATIONS.log or *_UAV_LOCATIONS.log file (generated by SimLogger)
    into a DataFrame. File format: '#auto generated file!' header followed by rows of
    time;id;x_pos;y_pos
    """
    data = pd.read_csv(file_path, sep=';', header=None, skiprows=1,
                        names=['time', id_column, 'x', 'y'])
    # ONAT: round so that timestamps sampled via repeated event rescheduling (UAVs)
    # line up with timestamps computed via direct multiplication (users/SAR).
    data['time'] = data['time'].round(2)
    return data


def generate_user_location_heatmap_video(scenario=None, num_devices=None, iteration=1,
                                          grid_size=40, fps=5, output_path=None):
    """
    Generates a video showing how the spatial distribution (heat map) of the users changes
    throughout the simulation, with the UAVs overlaid as markers colored by the service they
    host, and the world events (EVENTS.log) drawn as circles while they are active: the solid
    circle is the radius users request inside, the dashed one the radius users are drawn from.
    """
    config = get_configuration()
    folder_path = config['folder_path']
    output_folder_path = config['output_folder_path']
    orchestrator_policy = config['orchestrator_policy']

    if scenario is None:
        scenario = config['scenario_types'][0]
    if num_devices is None:
        num_devices = config['max_devices']
    scenario_legend = config['legends'][config['scenario_types'].index(scenario)]

    file_name = f'SIMRESULT_DEFAULT_SCENARIO_{orchestrator_policy}_{scenario}_{num_devices}DEVICES_USER_LOCATIONS.log'
    file_path = os.path.join(folder_path, f'ite{iteration}', file_name)

    print(f"Reading user location log -> {file_path}")
    try:
        data = _read_location_log(file_path, id_column='device_id')
    except FileNotFoundError:
        print(f"Warning: File not found -> {file_path}")
        return

    time_steps = np.sort(data['time'].unique())
    if len(time_steps) == 0:
        print("No data found in the log file, aborting.")
        return

    uav_file_name = f'SIMRESULT_DEFAULT_SCENARIO_{orchestrator_policy}_{scenario}_{num_devices}DEVICES_UAV_LOCATIONS.log'
    uav_file_path = os.path.join(folder_path, f'ite{iteration}', uav_file_name)
    try:
        uav_data = _read_location_log(uav_file_path, id_column='uav_id')
        print(f"Reading UAV location log -> {uav_file_path}")
    except FileNotFoundError:
        print(f"Warning: UAV location file not found -> {uav_file_path} (video will not show UAVs)")
        uav_data = pd.DataFrame(columns=['time', 'uav_id', 'x', 'y'])

    events_file_name = f'SIMRESULT_DEFAULT_SCENARIO_{orchestrator_policy}_{scenario}_{num_devices}DEVICES_EVENTS.log'
    events_file_path = os.path.join(folder_path, f'ite{iteration}', events_file_name)
    try:
        events = _read_events_log(events_file_path)
        print(f"Reading events log -> {events_file_path}")
    except FileNotFoundError:
        print(f"Warning: events file not found -> {events_file_path} (video will not show events)")
        events = []

    # ONAT: a UAV hosting exactly one service gets that service's color (the legend names it); one
    # hosting several (ALL placement) is gray.
    services = list(get_services().keys())
    service_color = {s: _SERVICE_COLORS[i % len(_SERVICE_COLORS)] for i, s in enumerate(services)}
    service_names = get_services()
    placement_policy = config['service_placement_policy']
    uav_color = {}
    for uav_id in uav_data['uav_id'].unique():
        hosted = get_uav_hosted_services(int(uav_id), placement_policy)
        uav_color[uav_id] = service_color[hosted[0]] if len(hosted) == 1 else 'lightgray'

    x_edges = np.linspace(AREA_BOUNDS['x_min'], AREA_BOUNDS['x_max'], grid_size + 1)
    y_edges = np.linspace(AREA_BOUNDS['y_min'], AREA_BOUNDS['y_max'], grid_size + 1)

    # Pre-compute the 2D histogram (heat map) for every time step so that the
    # color scale can be normalized consistently across the whole video.
    heatmaps = []
    uav_positions = []
    uav_colors = []
    users_in_event = []  # per frame, how many users stand inside each event's radius
    for t in time_steps:
        frame_data = data[data['time'] == t]
        hist, _, _ = np.histogram2d(frame_data['x'], frame_data['y'], bins=[x_edges, y_edges])
        heatmaps.append(hist.T)

        uav_frame_data = uav_data[uav_data['time'] == t].sort_values('uav_id')
        uav_positions.append(uav_frame_data[['x', 'y']].to_numpy())
        uav_colors.append([uav_color[uav_id] for uav_id in uav_frame_data['uav_id']])

        users_in_event.append([
            int(np.count_nonzero((frame_data['x'] - e['x']) ** 2 + (frame_data['y'] - e['y']) ** 2 <= e['radius'] ** 2))
            for e in events])

    vmax = max(h.max() for h in heatmaps)

    fig, ax = plt.subplots(figsize=(7.4, 7.0))
    plt.rcParams.update({'font.family': 'Times New Roman', 'font.size': 11})

    im = ax.imshow(heatmaps[0], origin='lower', cmap='YlOrRd', vmin=0, vmax=vmax,
                    extent=[AREA_BOUNDS['x_min'], AREA_BOUNDS['x_max'],
                            AREA_BOUNDS['y_min'], AREA_BOUNDS['y_max']])
    # ONAT: UAVs (edge servers) plotted with their own marker, colored by hosted service.
    uav_scatter = ax.scatter(uav_positions[0][:, 0], uav_positions[0][:, 1],
                              c=uav_colors[0], marker='^', edgecolors='black', linewidths=0.6, s=90,
                              zorder=4)
    # ONAT: every event is drawn (while it is active) as a solid circle - the radius users request
    # inside - and a dashed one - the radius users are drawn from - plus a label with what it
    # requests and how many users currently stand inside its radius.
    event_artists = []
    for e in events:
        radius_circle = Circle((e['x'], e['y']), e['radius'], fill=False, edgecolor=_EVENT_COLOR,
                               linewidth=1.8, zorder=5, visible=False)
        attraction_circle = Circle((e['x'], e['y']), e['attraction_radius'], fill=False, edgecolor=_EVENT_COLOR,
                                   linewidth=0.8, linestyle='--', alpha=0.5, zorder=5, visible=False)
        label = ax.text(e['x'], e['y'] + e['radius'] + 12, '', ha='center', va='bottom', fontsize=8, zorder=6,
                        bbox=dict(facecolor='white', edgecolor=_EVENT_COLOR, alpha=0.85, boxstyle='round,pad=0.2'),
                        visible=False)
        ax.add_patch(radius_circle)
        ax.add_patch(attraction_circle)
        event_artists.append((radius_circle, attraction_circle, label))
    ax.set_xlim(AREA_BOUNDS['x_min'], AREA_BOUNDS['x_max'])
    ax.set_ylim(AREA_BOUNDS['y_min'], AREA_BOUNDS['y_max'])
    ax.set_xlabel('X Position (m)')
    ax.set_ylabel('Y Position (m)')
    title = ax.set_title(f'{scenario_legend} (t = {time_steps[0]:.0f}s)')

    legend_handles = [Line2D([0], [0], marker='^', color='none', markerfacecolor=color, markeredgecolor='black',
                             markersize=9, label=f"UAV hosting {', '.join(service_names[s])}")
                      for s, color in service_color.items() if placement_policy == 'SINGLE']
    if placement_policy != 'SINGLE':
        legend_handles.append(Line2D([0], [0], marker='^', color='none', markerfacecolor='lightgray',
                                     markeredgecolor='black', markersize=9, label='UAV hosting every service'))
    if events:
        legend_handles.append(Line2D([0], [0], color=_EVENT_COLOR, linewidth=1.8, label='Event radius (users request)'))
        legend_handles.append(Line2D([0], [0], color=_EVENT_COLOR, linewidth=0.8, linestyle='--', alpha=0.5,
                                     label='Event attraction radius'))
    ax.legend(handles=legend_handles, loc='upper center', bbox_to_anchor=(0.5, -0.1), ncol=3, fontsize=8, frameon=False)
    fig.colorbar(im, ax=ax, label='# of Clients')
    fig.subplots_adjust(left=0.1, right=0.95, top=0.94, bottom=0.17)

    def update(frame_index):
        t = time_steps[frame_index]
        im.set_data(heatmaps[frame_index])
        uav_scatter.set_offsets(uav_positions[frame_index])
        uav_scatter.set_facecolor(uav_colors[frame_index])
        for event_index, (e, (radius_circle, attraction_circle, label)) in enumerate(zip(events, event_artists)):
            is_active = e['start'] <= t < e['end']
            radius_circle.set_visible(is_active)
            attraction_circle.set_visible(is_active)
            label.set_visible(is_active)
            if is_active:
                label.set_text(f"{e['name']}: {e['request']}\n{users_in_event[frame_index][event_index]} users inside")
        title.set_text(f'{scenario_legend} (t = {t:.0f}s)')
        return (im, uav_scatter, title,
                *[artist for artists in event_artists for artist in artists])

    ani = animation.FuncAnimation(fig, update, frames=len(time_steps), blit=False)

    if output_path is None:
        os.makedirs(output_folder_path, exist_ok=True)
        output_path = os.path.join(output_folder_path, f'user_location_heatmap_{scenario}_{num_devices}DEVICES.mp4')

    ani.save(output_path, writer=animation.FFMpegWriter(fps=fps))
    print(f"Video saved to {output_path}")
    plt.close(fig)


def _parse_args():
    config = get_configuration()
    parser = argparse.ArgumentParser(
        description='Generate a video of the client density heat map over the course of the simulation.')
    parser.add_argument('--scenario', default=None, choices=config['scenario_types'],
                         help='Run to visualize, written <MOBILITY>_<PLACEMENT> (e.g. SERVICE_APF_SINGLE). '
                              'If omitted, a video is generated for every UAV mobility policy.')
    parser.add_argument('--num-devices', type=int, nargs='+', default=None,
                         help='Number(s) of mobile devices of the simulation to visualize. '
                              "If omitted, videos are generated for config.py's heatmap_video_devices list.")
    parser.add_argument('--iteration', type=int, default=1, help='Simulation iteration (ite<N>) to visualize.')
    parser.add_argument('--grid-size', type=int, default=40, help='Number of heat map bins per axis.')
    parser.add_argument('--fps', type=int, default=5, help='Frames per second of the generated video.')
    parser.add_argument('--output', default=None, help='Output video file path (only valid with a single --scenario and --num-devices).')
    return parser.parse_args()


if __name__ == '__main__':
    print("--- Generating: User Location Heat Map Video ---")
    args = _parse_args()
    config = get_configuration()

    # ONAT: render every UAV mobility policy unless the user asked for a specific one
    # (NO/RANDOM are skipped by default - see config.py's heatmap_video_scenarios).
    scenarios_to_render = [args.scenario] if args.scenario else config['heatmap_video_scenarios']
    # ONAT: default to config.py's heatmap_video_devices list so a single run covers the desired load cases.
    device_counts_to_render = args.num_devices if args.num_devices else config['heatmap_video_devices']
    single_output = len(scenarios_to_render) == 1 and len(device_counts_to_render) == 1
    for scenario in scenarios_to_render:
        for num_devices in device_counts_to_render:
            generate_user_location_heatmap_video(scenario=scenario, num_devices=num_devices,
                                                  iteration=args.iteration, grid_size=args.grid_size,
                                                  fps=args.fps,
                                                  output_path=args.output if single_output else None)
